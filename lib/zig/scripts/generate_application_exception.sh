set -euo pipefail

if [ "$#" -ne 2 ]; then
  echo "usage: $0 <compiler-output.zig> <destination.zig>" >&2
  exit 1
fi

input="$1"
output="$2"

python3 - "$input" "$output" <<'PY'
import sys

input_path, output_path = sys.argv[1:3]
text = open(input_path, encoding="utf-8").read()
marker = "pub const TApplicationException = struct {"
start = text.find(marker)
if start < 0:
    raise SystemExit(f"could not find {marker!r} in {input_path}")

depth = 0
end = start
for index in range(start, len(text)):
    char = text[index]
    if char == "{":
        depth += 1
    elif char == "}":
        depth -= 1
        if depth == 0:
            end = text.index(";", index) + 1
            break
else:
    raise SystemExit(f"unterminated struct in {input_path}")

struct = text[start:end]
struct = struct.replace("thrift.String", "types.String")
struct = struct.replace("thrift.internal.hash", "utils.hash")

header = """\
// Autogenerated from TApplicationException.thrift by scripts/generate_application_exception.sh
// DO NOT EDIT — run `make -C lib/zig generate` to regenerate

const std = @import("std");
const protocol = @import("../../protocol/mod.zig");
const types = @import("../types.zig");
const utils = @import("../../internal/struct_utilities.zig");

const TProtocol = protocol.TProtocol;
const TFieldIdentifier = protocol.TFieldIdentifier;
const TStructIdentifier = protocol.TStructIdentifier;
const TType = protocol.TType;
const ProtocolError = protocol.ProtocolError;

const Allocator = std.mem.Allocator;

"""

open(output_path, "w", encoding="utf-8", newline="\n").write(header + struct + "\n")
PY
